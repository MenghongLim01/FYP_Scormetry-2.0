        <h1>Privacy Policy</h1>
        <p class="sub">How Scormetry 2.0 collects, uses, and protects your information.</p>

        <h2>1. Information We Collect</h2>
        <p>We collect the information needed to run academic evaluations: your name and email (for your account), the subjects, teams, and roles you belong to, documents you upload, and the scores and feedback recorded during evaluations.</p>

        <h2>2. How We Use It</h2>
        <p>Your information is used solely to operate the platform — authenticating you, controlling access to documents, running rubric-based scoring, sending notifications (e.g., document submitted, results released), and producing evaluation records for your institution.</p>

        <h2>3. Google Account &amp; Calendar Access</h2>
        <p>When you sign in with Google we receive your name, email address, and profile to create or match your Scormetry account. If you choose to connect Google Calendar, we request the <code>calendar.events</code> scope only to create, update, and remove the calendar events for defense sessions you are assigned to. We never read your existing calendar events and never share this data with third parties. You can disconnect Google Calendar at any time, which stops all syncing.</p>

        <h2>4. Document &amp; Score Confidentiality</h2>
        <p>Student documents and manuscripts are stored privately and are visible only to the student's team, the subject instructor, and judges assigned to that team. Reviews are hidden from students until results are released. Score overrides and review unlocks are logged for audit.</p>

        <h2>5. Notifications</h2>
        <p>We send notifications by email and in-app to keep you informed of relevant events. These are tied to your account activity and role; we do not send marketing email.</p>

        <h2>6. Data Retention</h2>
        <p>Evaluation records are retained for academic administration in line with your institution's policy. You may request information about your data through your instructor or administrator.</p>

        <h2>7. Security</h2>
        <p>Access is role-based and assignment-based. An optional email login code (one-time passcode) is available. We take reasonable measures to protect data, though no system can guarantee absolute security.</p>

        <h2>8. Third Parties</h2>
        <p>AI-assisted rubric extraction may process the Defense Rubric file you upload. Email delivery and hosting are handled by standard service providers. We do not sell personal data.</p>

        <h2>9. Contact</h2>
        <p>For any questions about this policy or your data, contact the developer at <a href="mailto:limmenghong678@gmail.com">limmenghong678@gmail.com</a>.</p>

